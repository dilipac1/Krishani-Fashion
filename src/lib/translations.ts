export function formatCategoryName(categoryName: string, lang: Language): string {
  if (!categoryName) return '';
  if (categoryName === 'All' || categoryName === 'සියල්ල') {
    return lang === 'si' ? 'සියල්ල' : 'All';
  }

  const knownCategories: Record<string, { en: string; si: string }> = {
    'ඇඳ ඇතිරිලි (Bed Sheets)': { en: 'Bed Sheets', si: 'ඇඳ ඇතිරිලි' },
    'කොට්ට උර (Pillow Cases)': { en: 'Pillow Cases', si: 'කොට්ට උර' },
    'දුපොට් / කුෂන් (Duvets)': { en: 'Duvets & Cushions', si: 'දුපොට් / කුෂන්' },
    'මැට්ට්‍රස් ප්‍රෝටෙක්ටර්': { en: 'Mattress Protectors', si: 'මැට්ට්‍රස් ප්‍රෝටෙක්ටර්' },
    'Other': { en: 'Other', si: 'වෙනත්' }
  };

  if (knownCategories[categoryName]) {
    return knownCategories[categoryName][lang];
  }

  const match = categoryName.match(/\(([^)]+)\)/);
  if (lang === 'en') {
    if (match && match[1]) {
      return match[1].trim();
    }
    const cleaned = categoryName.replace(/[\u0D80-\u0DFF]+/g, '').replace(/[()]+/g, '').trim();
    return cleaned || categoryName;
  } else {
    const sinhalaPart = categoryName.replace(/\([^)]*\)/g, '').trim();
    return sinhalaPart || categoryName;
  }
}
